"""คำตอบพื้นฐานที่ไม่ต้องใช้ LLM เป็นด่านสุดท้ายเมื่อไม่มีผู้ให้บริการที่ใช้ได้"""

NAME = "rule_based"


def reply(query, properties):
    if query.intent == "consign":
        return "ฝากขายทรัพย์กับ Finding House ได้เลยครับ กรอกข้อมูลทรัพย์และแนบรูป แล้วเจ้าหน้าที่จะติดต่อกลับ"
    if query.intent == "contact":
        return "ติดต่อเจ้าหน้าที่ได้จากหน้าติดต่อเราครับ"
    if properties:
        return f"พบทรัพย์ที่น่าจะตรงกับที่ต้องการ {len(properties)} รายการครับ"
    if query.has_criteria:
        return "ยังไม่พบทรัพย์ที่ตรงเงื่อนไขนี้ครับ ลองปรับเงื่อนไข หรือดูรายการทรัพย์ทั้งหมดได้"
    if query.intent == "greeting":
        return "สวัสดีครับ ยินดีช่วยหาทรัพย์ บอกประเภท ทำเล หรืองบประมาณได้เลย เช่น คอนโดให้เช่า งบ 2 หมื่น"
    return "บอกประเภททรัพย์ ทำเล หรืองบประมาณที่สนใจได้เลยครับ เช่น บ้านเดี่ยว 3 ห้องนอน งบ 5 ล้าน หรือพิมพ์รหัสทรัพย์"
